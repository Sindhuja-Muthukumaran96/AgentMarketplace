/**
 * Deterministic "fake LLM reasoning" used by the bundled Mock provider so the
 * full agent flow (RAG -> tool calls -> generation -> execution -> retry ->
 * report) can be demonstrated end-to-end with zero API keys and zero network
 * calls to an LLM — calibrated against the sample SauceDemo-style Playwright
 * repository used in this project's own demos.
 *
 * IMPORTANT: this Mock is a demo convenience, not a general-purpose reasoner.
 * It recognizes a handful of acceptance-criteria keyword patterns tied to a
 * specific sample Page Object API shape. For genuinely new/arbitrary
 * repositories, use `--llm-provider openai`, which reasons generically via the
 * same tool-calling protocol regardless of the target repo's Page Object shapes.
 */

export type ScenarioKey =
  | 'add-to-cart'
  | 'remove-item-from-cart'
  | 'invalid-login'
  | 'complete-purchase'
  | 'logout';

export function detectScenario(acceptanceCriteria: string): ScenarioKey {
  const ac = acceptanceCriteria.toLowerCase();
  if (ac.includes('remove') && ac.includes('cart')) return 'remove-item-from-cart';
  if ((ac.includes('invalid') || ac.includes('incorrect') || ac.includes('wrong')) &&
    (ac.includes('login') || ac.includes('credential'))) return 'invalid-login';
  if (ac.includes('checkout') || ac.includes('purchase') || ac.includes('place order') || ac.includes('complete order')) return 'complete-purchase';
  if (ac.includes('logout') || ac.includes('log out') || ac.includes('sign out')) return 'logout';
  return 'add-to-cart';
}

export function scenarioToPageObject(scenario: ScenarioKey): string {
  switch (scenario) {
    case 'remove-item-from-cart': return 'CartPage';
    case 'invalid-login': return 'LoginPage';
    case 'complete-purchase': return 'CheckoutPage';
    case 'logout':
    case 'add-to-cart':
    default: return 'DashboardPage';
  }
}

export interface GeneratedScenario {
  fileName: string;
  suiteName: string;
  testCode: string;
}

export function generateScenarioCode(scenario: ScenarioKey, variant: 'initial' | 'fixed'): GeneratedScenario {
  switch (scenario) {
    case 'add-to-cart':
      return {
        fileName: 'add-single-product-to-cart',
        suiteName: 'Dashboard - Product Inventory',
        testCode: `import { test, expect } from '@fixtures/pageFixtures';

/**
 * Generated by the Test Script Design Agent from an acceptance criteria input.
 */
test.describe('Dashboard - Product Inventory', () => {
  test('should add a single product to the cart', async ({ dashboardPage }) => {
    // Arrange
    await dashboardPage.waitForDashboard();

    // Act
    await dashboardPage.addProductToCart(0);

    // Assert
    expect(await dashboardPage.isCartBadgeVisible()).toBeTruthy();
    expect(await dashboardPage.getCartItemCount()).toBe(1);
  });
});
`
      };

    case 'remove-item-from-cart':
      return {
        fileName: 'remove-item-from-cart',
        suiteName: 'Shopping Workflow - Cart Management',
        testCode:
          variant === 'initial'
            ? `import { test, expect } from '@fixtures/pageFixtures';

/**
 * Generated by the Test Script Design Agent from an acceptance criteria input.
 */
test.describe('Shopping Workflow - Cart Management', () => {
  test('should allow removing an item from the cart', async ({ dashboardPage, cartPage }) => {
    // Arrange
    await dashboardPage.waitForDashboard();
    await dashboardPage.addProductToCart(0);
    await dashboardPage.addProductToCart(1);
    await dashboardPage.goToCart();

    // Act
    await cartPage.removeItemByIndex(0);

    // Assert
    const finalCount = await dashboardPage.getCartItemCount();
    expect(finalCount).toBe(0);
  });
});
`
            : `import { test, expect } from '@fixtures/pageFixtures';

/**
 * Generated by the Test Script Design Agent from an acceptance criteria input.
 * Fixed after execution feedback: the cart count after removing one item is
 * relative to how many items were added, not an absolute zero.
 */
test.describe('Shopping Workflow - Cart Management', () => {
  test('should allow removing an item from the cart', async ({ dashboardPage, cartPage }) => {
    // Arrange
    await dashboardPage.waitForDashboard();
    await dashboardPage.addProductToCart(0);
    await dashboardPage.addProductToCart(1);
    await dashboardPage.goToCart();
    const initialCount = await dashboardPage.getCartItemCount();

    // Act
    await cartPage.removeItemByIndex(0);

    // Assert
    const finalCount = await dashboardPage.getCartItemCount();
    expect(finalCount).toBe(initialCount - 1);
  });
});
`
      };

    case 'invalid-login':
      return {
        fileName: 'invalid-login-error-message',
        suiteName: 'Authentication - Login',
        testCode: `import { test, expect } from '@fixtures/pageFixtures';
import { TestDataFactory } from '@utils/testDataFactory';

/**
 * Generated by the Test Script Design Agent from an acceptance criteria input.
 */
test.describe('Authentication - Login', () => {
  test('should display an error message when logging in with invalid credentials', async ({ loginPage }) => {
    // Arrange
    const invalidUser = TestDataFactory.getInvalidUser();
    await loginPage.navigateToLoginPage();

    // Act
    await loginPage.login(invalidUser.username, invalidUser.password);

    // Assert
    expect(await loginPage.isErrorMessageVisible()).toBeTruthy();
    const errorMessage = await loginPage.getErrorMessage();
    expect(errorMessage).toContain('Epic sadface');
  });
});
`
      };

    case 'complete-purchase':
      return {
        fileName: 'complete-purchase-single-product',
        suiteName: 'Shopping Workflow - Complete Purchase',
        testCode: `import { test, expect } from '@fixtures/pageFixtures';
import { TestDataFactory } from '@utils/testDataFactory';

/**
 * Generated by the Test Script Design Agent from an acceptance criteria input.
 */
test.describe('Shopping Workflow - Complete Purchase', () => {
  test('should complete a purchase for a single product end to end', async ({
    dashboardPage,
    cartPage,
    checkoutPage
  }) => {
    // Arrange
    await dashboardPage.waitForDashboard();

    // Act - add product and proceed to checkout
    await dashboardPage.addProductToCart(0);
    await dashboardPage.goToCart();
    expect(await cartPage.isCartPageLoaded()).toBeTruthy();
    await cartPage.checkout();
    await checkoutPage.waitForCheckoutStepOne();

    const checkoutInfo = TestDataFactory.getCheckoutInfo();
    await checkoutPage.fillCheckoutInfo(checkoutInfo.firstName, checkoutInfo.lastName, checkoutInfo.postalCode);
    await checkoutPage.continueCheckout();
    await checkoutPage.waitForCheckoutOverview();

    // Assert overview then complete the order
    expect(await checkoutPage.isCheckoutOverviewLoaded()).toBeTruthy();
    await checkoutPage.completeOrder();

    // Assert confirmation
    expect(await checkoutPage.isOrderConfirmationVisible()).toBeTruthy();
    const confirmationMessage = await checkoutPage.getConfirmationMessage();
    expect(confirmationMessage).toContain('Thank you');
  });
});
`
      };

    case 'logout':
    default:
      return {
        fileName: 'logout-from-dashboard',
        suiteName: 'Dashboard - Product Inventory',
        testCode: `import { test, expect } from '@fixtures/pageFixtures';

/**
 * Generated by the Test Script Design Agent from an acceptance criteria input.
 */
test.describe('Dashboard - Product Inventory', () => {
  test('should log out successfully from the dashboard', async ({ dashboardPage, loginPage }) => {
    // Arrange
    await dashboardPage.waitForDashboard();

    // Act
    await dashboardPage.logout();

    // Assert
    expect(await loginPage.isLoginPageLoaded()).toBeTruthy();
  });
});
`
      };
  }
}
